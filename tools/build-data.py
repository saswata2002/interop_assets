#!/usr/bin/env python3
"""ae-dump.json (tools/export-ae-keys.jsx, run inside After Effects) ->
src/switching-to-minutes.data.js

Keeps only what the canvas scene animates: every layer's transform keys,
exactly as AE stores them (value, interpolation type, temporal ease), with
all times moved onto the master clock (the "03- Exit" copy of the master
starts its layers at -4.9333 s, so its key times are shifted back by that).
Static geometry lives in the scene file; this is the motion only.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
dump = json.load(open(os.path.join(HERE, 'ae-dump.json')))

COMPS = {
    'main':  '03- Exit',
    'title': 'Switching to (precomp)',
    'crate': 'Crate plate (precomp)',
}
PROPS = ['Anchor Point', 'Position', 'Position_0', 'Position_1', 'Scale', 'Rotate Z', 'Opacity']


def r(v, dp=6):
    if isinstance(v, list):
        return [r(x, dp) for x in v]
    return round(v, dp) if isinstance(v, float) else v


def prop(p, shift):
    if 'k' not in p:
        v = p['v']
        return {'v': r(v[:2] if isinstance(v, list) else v)}
    keys = []
    for k in p['k']:
        v = k['v']
        o = {'t': r(k['t'] + shift), 'v': r(v[:2] if isinstance(v, list) else v),
             'i': k['ii'], 'o': k['oi']}
        if 'ie' in k:
            o['ie'] = r(k['ie'][:2])
            o['oe'] = r(k['oe'][:2])
        keys.append(o)
    return {'k': keys}


out = {}
for key, name in COMPS.items():
    comp = dump[name]
    layers = {}
    for L in comp['layers']:
        shift = -L['st']          # layer keys are in comp time; put them on the master clock
        tr = {}
        for pn in PROPS:
            if pn in L['tr']:
                tr[pn.replace(' ', '')] = prop(L['tr'][pn], shift)
        layers[L['name']] = tr
    out[key] = layers

js = ('// Generated by tools/build-data.py from the After Effects comp\n'
      '// "Switching to Minutes - Sequence (Intro + Loop x2 + Exit)" (Back In Stock.aep).\n'
      '// Every transform key as AE stores it, times in seconds on the master clock.\n'
      '// Do not edit by hand: re-export from AE and re-run the script.\n'
      'export const KEYS = ' + json.dumps(out, separators=(',', ':')) + ';\n')
dst = os.path.join(HERE, '..', 'src', 'switching-to-minutes.data.js')
open(dst, 'w').write(js)
print('wrote', os.path.normpath(dst), len(js), 'bytes')
